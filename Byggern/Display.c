void display_all_pages() {
	for(int i = 0; i < 8; i++){
		uint8_t page_start []= {0xb0 | i};
		display_cmd(page_start,1);
		//printf("%c",ext_ram[i*128]);
		display_data(&ext_ram[i*128], 128);
	}
}

